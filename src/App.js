// Shareable per-game links: playdraft.app/#/four-downs and /#/start-sit.
// Hash routing needs no server rewrite, so these work today. Each game can be
// posted separately, and referrers attributed separately.
const ROUTES={"#/start-sit":"startsit","#/four-downs":"game","#/locker":"locker","#/how":"howto"};
const SCREEN_HASH={startsit:"#/start-sit",game:"#/four-downs",locker:"#/locker",howto:"#/how",home:"#/"};

export default function App() {
  // CRITICAL: Inject viewport meta tag for mobile rendering
  useEffect(() => {
    let viewport = document.querySelector('meta[name="viewport"]');
    if (!viewport) {
      viewport = document.createElement('meta');
      viewport.name = 'viewport';
      document.head.appendChild(viewport);
    }
    viewport.content = 'width=device-width, initial-scale=1, maximum-scale=1, user-scalable=no, viewport-fit=cover';
  }, []);

  useEffect(() => {
    try {
      let anonId = localStorage.getItem('pd_anon_id');
      if (!anonId) {
        anonId = Math.random().toString(36).slice(2) + Date.now().toString(36);
        localStorage.setItem('pd_anon_id', anonId);
      }
      captureSource();
      if (localStorage.getItem('pd_me') === '1') return;   // owner's own visits never count
      fetch('/api/track', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ id: anonId, src: localStorage.getItem('pd_src') || 'unknown' }),
      }).catch(() => {});
    } catch {}
  }, []);

  const [dark,setDark]=useState(false);
  const [showOnboarding,setShowOnboarding]=useState(()=>{
    try { return !localStorage.getItem("pd_onboarding_seen"); } catch { return true; }
  });
  const [screen,setScreen]=useState(()=>{
    try{ return ROUTES[window.location.hash]||"home"; }catch{ return "home"; }
  });
  useEffect(()=>{
    const h=SCREEN_HASH[screen]||"#/";
    try{ if(window.location.hash!==h) window.history.replaceState(null,"",h); }catch{}
  },[screen]);
  useEffect(()=>{
    const onHash=()=>setScreen(ROUTES[window.location.hash]||"home");
    window.addEventListener("hashchange",onHash);
    return ()=>window.removeEventListener("hashchange",onHash);
  },[]);
  const [showScoring,setShowScoring]=useState(false);
  // Help, scoring and the Locker Room open on the game the player came from,
  // and BACK returns them there.
  const [helpFor,setHelpFor]=useState("fourdowns");
  const [helpFrom,setHelpFrom]=useState("home");
  const openHelp=target=>{
    if(!["howto","scoring","locker"].includes(screen)){
      setHelpFor(screen==="startsit"?"startsit":"fourdowns");
      setHelpFrom(screen);
    }
    setScreen(target);
  };
  const closeHelp=()=>setScreen(helpFrom==="game"||helpFrom==="startsit"?helpFrom:"home");
  const [mode,setMode]=useState("daily");
  // Server-side "opened" for each game, so the stats email can compare them
  // on equal terms. Fires however the player arrived (button or deep link).
  // Start/Sit sends its own lineup_open from StartSit.js.
  useEffect(()=>{
    if(screen==="game" && mode==="daily") trackEvent("fd_open");
  },[screen,mode]);
  const [practicePuzzle,setPracticePuzzle]=useState(()=>getRandomPracticePuzzle()||getTodaysPuzzle());
  const [recentPractice,setRecentPractice]=useState([]);
  const featuredPuzzle = getFeaturedPuzzle();
  const puzzle = mode==="featured" ? (featuredPuzzle||getTodaysPuzzle())
               : (mode==="daily" ? getTodaysPuzzle() : practicePuzzle);
  // Featured is entered only from the banner or the solve-page CTA —
  // never from the header toggle. Keeps daily the default route in.
  const playFeatured = () => {
    if(!getFeaturedPuzzle()) return;
    setMode("featured");
    setScreen("game");
  };
  const handleModeChange=m=>{
    setMode(m);
    setScreen("home");
    // When switching to practice, pick a fresh puzzle
    if(m==="practice"){
      const newRecent=[...recentPractice,practicePuzzle.id].slice(-Math.max(1,PUZZLES.length-2));
      setRecentPractice(newRecent);
      setPracticePuzzle(getRandomPracticePuzzle(newRecent)||practicePuzzle);
    }
  };
  const handleFinish=()=>{
    if(mode==="featured"){
      // Featured is a one-off, not a loop — always return to the daily home.
      setMode("daily");
      setScreen("home");
      return;
    }
    if(mode==="practice"){
      // Pick a new random puzzle for next round, stay in game (don't go home)
      const newRecent=[...recentPractice,practicePuzzle.id].slice(-Math.max(1,PUZZLES.length-2));
      setRecentPractice(newRecent);
      setPracticePuzzle(getRandomPracticePuzzle(newRecent)||practicePuzzle);
    } else {
      setScreen("home");
    }
  };

  return (
    <>
      <style>{`
                body{font-family:'Barlow',system-ui,-apple-system,sans-serif;-webkit-font-smoothing:antialiased;}
        button,input,select,textarea{font-family:inherit;}
        *{box-sizing:border-box;margin:0;padding:0;}
        html,body{background:${dark?"#0B0F19":"#F3F4F6"};margin:0;padding:0;min-height:100vh;}
        @keyframes popIn{from{opacity:0;transform:translateY(-10px) scale(0.97);}to{opacity:1;transform:translateY(0) scale(1);}}
        @keyframes fadeUp{from{opacity:0;transform:translateY(8px);}to{opacity:1;transform:translateY(0);}}
        @keyframes toastIn{from{opacity:0;transform:translateX(-50%) translateY(-6px);}to{opacity:1;transform:translateX(-50%) translateY(0);}}
        @keyframes shake{0%,100%{transform:translateX(0);}20%{transform:translateX(-5px);}40%{transform:translateX(5px);}60%{transform:translateX(-3px);}80%{transform:translateX(3px);}}
        button:focus-visible{outline:2px solid #B45309;outline-offset:2px;}
        button{-webkit-tap-highlight-color:transparent;}
      `}</style>
      <Header dark={dark} onDark={()=>setDark(d=>!d)} onStats={()=>openHelp("locker")} onHome={()=>setScreen("home")} onHow={()=>openHelp("howto")} onScoring={()=>openHelp("scoring")} mode={mode} onMode={handleModeChange} showModes={screen==="game"&&mode!=="featured"}
        screen={screen} onStartSit={()=>setScreen("startsit")}
        onFourDowns={()=>{if(screen==="game")return;if(mode==="featured")setMode("daily");evFourDowns("opened",{mode:mode==="featured"?"daily":mode});setScreen("game");}}/>
      {screen==="home"&&<Landing onPlay={()=>{if(mode==="featured")setMode("daily");evFourDowns("opened",{mode});setScreen("game");}} onPlayLineup={()=>setScreen("startsit")} onPlayFeatured={playFeatured} onPractice={()=>{handleModeChange("practice");setScreen("game");}} dark={dark} mode={mode==="featured"?"daily":mode}/>}
      {screen==="game"&&<Game key={`${puzzle.id}-${mode}`} puzzle={puzzle} dark={dark} mode={mode} onFinish={handleFinish} onPlayFeatured={playFeatured}/>}
      {screen==="howto"&&<HowTo dark={dark} game={helpFor} onClose={closeHelp} onPlay={g=>{if(g==="startsit")setScreen("startsit");else{setMode("daily");setScreen("game");}}}/>}
      {screen==="scoring"&&<ScoringPage dark={dark} game={helpFor} onClose={closeHelp}/>}
      {screen==="locker"&&<LockerRoom dark={dark} game={helpFor} onClose={closeHelp} onPlay={()=>{setMode("daily");setScreen("game");}} onPlayLineup={()=>setScreen("startsit")}/>}
      {screen==="startsit"&&<Suspense fallback={<div style={{minHeight:"100vh"}}/>}><StartSit dark={dark} onExit={()=>setScreen("home")} mode={playedLineupToday()?"practice":"daily"}/></Suspense>}
      {/* The tutorial explains Four Downs, so it waits until someone opens
          Four Downs. Showing it to a Start/Sit deep link (every ad click)
          described the wrong game. */}
      {showOnboarding&&screen==="game"&&<OnboardingModal dark={dark} onClose={()=>setShowOnboarding(false)}/>}
      <Analytics />
    </>
  );
}

