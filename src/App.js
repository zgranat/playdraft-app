function Game({puzzle,dark,onFinish,mode,onPlayFeatured}) {
  const [tiles,setTiles]=useState(()=>shuffle(puzzle.players));
  const [selected,setSelected]=useState([]);
  const [solved,setSolved]=useState([]);
  const [wrong,setWrong]=useState(0);
  const [timeMs,setTimeMs]=useState(0);
  const [timerOn,setTimerOn]=useState(true);
  const [over,setOver]=useState(false);
  const [shaking,setShaking]=useState([]);
  const [toast,setToast]=useState(null);
  const [showResult,setShowResult]=useState(false);
  const [revealedGroups,setRevealedGroups]=useState([]);  // Auto-reveal on loss
  const [triedCombos,setTriedCombos]=useState([]);  // Track previously tried combinations
  const toastRef=useRef(null);
  const bg=dark?"#0B0F19":"#F3F4F6";

  useEffect(()=>{ if(mode==="daily") trackEvent('start'); else if(mode==="featured") trackEvent('featured_start',{featured:puzzle.id}); },[]);

  const showToast=(msg,dur=1800)=>{clearTimeout(toastRef.current);setToast(typeof msg==="string"?{title:msg}:msg);toastRef.current=setTimeout(()=>setToast(null),dur);};
  const handleTile=name=>{if(over)return;setSelected(prev=>prev.includes(name)?prev.filter(p=>p!==name):prev.length<4?[...prev,name]:prev);};

  const handleSubmit=()=>{
    if(selected.length!==4||over)return;
    // Check if this exact combination was already tried (no penalty)
    const comboKey=[...selected].sort().join("|");
    if(triedCombos.includes(comboKey)){
      showToast("ALREADY RAN THAT PLAY 🔁",1800);
      return;
    }
    const group=puzzle.groups.find(g=>selected.every(p=>g.players.includes(p))&&g.players.every(p=>selected.includes(p)));
    if(group){
      const ns=[...solved,group];setSolved(ns);setSelected([]);
      showToast(["LOCKED IN 🔒","TOUCHDOWN! 🏈","YOU GOT IT!","NICE READ! 🎯","FIRST DOWN! ✅"][Math.floor(Math.random()*5)]);
      if(ns.length===4){
        setTimerOn(false);setOver(true);
        // Show result panel after last category lock-in animation completes
        setTimeout(()=>setShowResult(true),900);
        if(mode==="daily"){ recordDailyResult(true, fmt(timeMs), timeMs, wrong); trackEvent('win',{wrong}); }
        else if(mode==="featured"){ recordFeaturedResult(puzzle, true, timeMs, wrong); trackEvent('featured_win',{wrong,featured:puzzle.id}); }
      }
    } else {
      const oneAway=puzzle.groups.some(g=>selected.filter(p=>g.players.includes(p)).length===3);
      setShaking([...selected]);setTimeout(()=>setShaking([]),550);
      const nw=wrong+1;setWrong(nw);
      const left=4-nw, downs=`${left} DOWN${left===1?"":"S"} LEFT`;
      if(oneAway){
        showToast({title:"ONE AWAY 👀",sub:`3 OF THESE 4 CONNECT · ${downs}`,tone:"warn"},2400);
      } else {
        const flavor=["FUMBLE 😬","INTERCEPTION! 🙈","DELAY OF GAME 🚩","TURNOVER! 😤","SACKED! 🏃"][Math.floor(Math.random()*5)];
        showToast({title:flavor,sub:`NOT CLOSE · ${downs}`,tone:"bad"},2200);
      }
      setTriedCombos(prev=>[...prev,comboKey]);
      // Keep tiles selected so user can swap one without re-picking all 4
      if(nw>=4){
        setTimerOn(false);setOver(true);
        // Reveal remaining groups one at a time, easiest first
        const remaining = puzzle.groups
          .filter(g=>!solved.some(s=>s.id===g.id))
          .sort((a,b)=>a.difficulty-b.difficulty);
        remaining.forEach((g,i)=>{
          setTimeout(()=>setRevealedGroups(prev=>[...prev,g]),700+(i*600));
        });
        // Show result panel after all reveals complete
        setTimeout(()=>setShowResult(true),700+(remaining.length*600)+400);
        if(mode==="daily"){ recordDailyResult(false, null, null, nw); trackEvent('loss',{wrong:nw}); }
        else if(mode==="featured"){ recordFeaturedResult(puzzle, false, null, nw); trackEvent('featured_loss',{wrong:nw,featured:puzzle.id}); }
      }
    }
  };

  const unsolved=tiles.filter(p=>!solved.some(g=>g.players.includes(p)) && !revealedGroups.some(g=>g.players.includes(p)));

  return (
    <div style={{background:bg,display:"flex",flexDirection:"column",padding:"16px 12px 32px"}}>
      <div style={{maxWidth:"460px",margin:"0 auto",width:"100%",display:"flex",flexDirection:"column"}}>

        {/* Guest contributor banner — renders only when puzzle.contributor exists */}
        <ContributorBanner contributor={puzzle.contributor} dark={dark}/>

        {/* Top bar */}
        <div style={{display:"flex",alignItems:"center",justifyContent:"space-between",marginBottom:"12px"}}>
          <div style={{fontFamily:"'Barlow Condensed','Arial Narrow',sans-serif",fontSize:"13px",letterSpacing:"1px",color:dark?"#666":"#999"}}>{puzzle.title}</div>
          <Timer running={timerOn} onTick={setTimeMs} dark={dark}/>
          <div style={{textAlign:"right"}}>
            <div style={{fontFamily:"'Barlow Condensed','Arial Narrow',sans-serif",fontSize:"8px",letterSpacing:"0.7px",color:dark?"#444":"#aaa"}}>DOWNS</div>
            <div style={{display:"flex",gap:"4px",justifyContent:"flex-end",marginTop:"2px"}}>
              {[...Array(4)].map((_,i)=>(
                <div key={i} style={{width:"10px",height:"10px",borderRadius:"50%",background:i<(4-wrong)?"#B45309":(dark?"#222":"#E5E7EB"),transition:"background 0.3s"}}/>
              ))}
            </div>
          </div>
        </div>

        {/* Objective + progress */}
        <div style={{fontFamily:"'Barlow Condensed','Arial Narrow',sans-serif",fontSize:"11px",letterSpacing:"0.7px",color:dark?"#666":"#999",textAlign:"center",marginBottom:"10px"}}>
          FIND 4 GROUPS OF 4 CONNECTED PLAYERS · <span style={{color:"#B45309"}}>{solved.length}/4 FOUND</span>
        </div>

        {/* Solved + auto-revealed (on loss) rows — all in difficulty order */}
        {[...solved, ...revealedGroups].sort((a,b)=>a.difficulty-b.difficulty).map(g=>(
          <SolvedRow key={g.id} group={g} dark={dark}/>
        ))}

        {/* Grid — fills available space */}
        {unsolved.length>0&&(
          <div style={{display:"grid",gridTemplateColumns:"repeat(4,1fr)",gap:"8px",marginBottom:"16px"}}>
            {unsolved.map(name=>(
              <Tile key={name} name={name} selected={selected.includes(name)} onClick={()=>handleTile(name)} dark={dark} shaking={shaking.includes(name)}/>
            ))}
          </div>
        )}

        {/* Controls — bottom anchored, thumb-friendly */}
        {!over&&(
          <div style={{display:"flex",flexDirection:"column",gap:"8px"}}>
            <div style={{display:"flex",gap:"8px"}}>
              <button onClick={()=>setTiles(shuffle(unsolved))} style={{flex:1,fontFamily:"'Barlow Condensed','Arial Narrow',sans-serif",fontSize:"14px",letterSpacing:"0.7px",padding:"16px",background:"transparent",color:dark?"#888":"#888",border:`1px solid ${dark?"#2a2a2a":"#ccc"}`,borderRadius:"8px",cursor:"pointer",WebkitTapHighlightColor:"transparent"}}>SHUFFLE</button>
              <button onClick={()=>setSelected([])} disabled={!selected.length} style={{flex:1,fontFamily:"'Barlow Condensed','Arial Narrow',sans-serif",fontSize:"14px",letterSpacing:"0.7px",padding:"16px",background:"transparent",color:selected.length?(dark?"#E5E7EB":"#111827"):"#888",border:`1px solid ${selected.length?(dark?"#444":"#999"):(dark?"#222":"#ddd")}`,borderRadius:"8px",cursor:selected.length?"pointer":"default",WebkitTapHighlightColor:"transparent"}}>CLEAR</button>
              <button onClick={handleSubmit} disabled={selected.length!==4} style={{flex:2,fontFamily:"'Barlow Condensed','Arial Narrow',sans-serif",fontSize:"16px",letterSpacing:"0.7px",padding:"16px",background:selected.length===4?"#B45309":(dark?"#1B2433":"#E5E7EB"),color:selected.length===4?"#fff":(dark?"#333":"#bbb"),border:"none",borderRadius:"8px",cursor:selected.length===4?"pointer":"default",transition:"background 0.15s",WebkitTapHighlightColor:"transparent"}}>SUBMIT</button>
            </div>
          </div>
        )}

        {/* Toast */}
        {toast&&(
          <div style={{position:"fixed",top:"64px",left:"50%",transform:"translateX(-50%)",background:dark?"#1a1a1a":"#111827",padding:"10px 22px",borderRadius:"8px",boxShadow:"0 4px 20px rgba(0,0,0,0.5)",zIndex:200,textAlign:"center",whiteSpace:"nowrap",animation:"toastIn 0.2s ease",border:`1px solid ${toast.tone==="bad"?"rgba(139,26,42,0.9)":"rgba(180,83,9,0.4)"}`}}>
            <div style={{fontFamily:"'Barlow Condensed','Arial Narrow',sans-serif",fontSize:"16px",letterSpacing:"1px",color:toast.tone==="bad"?"#D9788A":"#B45309"}}>{toast.title}</div>
            {toast.sub&&<div style={{fontFamily:"'Barlow Condensed','Arial Narrow',sans-serif",fontSize:"10px",letterSpacing:"0.7px",color:"#8a8a8a",marginTop:"3px"}}>{toast.sub}</div>}
          </div>
        )}

        {showResult&&<ResultPanel puzzle={puzzle} solved={[...solved,...revealedGroups]} solvedOnly={solved} wrong={wrong} ms={timeMs} dark={dark} onPlayAgain={onFinish} won={solved.length===4} mode={mode} onPlayFeatured={onPlayFeatured}/>}
      </div>
    </div>
  );
}

